"""Built-in personality preset library — immutable, classified by
category, adult presets flagged as metadata (never runtime-trusted).

Each preset carries sparse ``traits`` (only signature sliders differ
from the 50 midpoint), sparse ``voice`` controls, and a
``greeting_style`` tag the greeting service maps onto personality-aware
templates. Editing a preset in the Studio produces a custom copy —
presets themselves are never mutated.
"""
from __future__ import annotations

# greeting_style values map to template families in greetings.py:
#   default, warm, professional, playful, nerdy, calm, sassy, flirty


def _P(id_: str, name: str, category: str, style: str,
       traits: dict, voice: dict | None = None,
       adult_only: bool = False) -> dict:
    return {"id": id_, "name": name, "category": category,
            "greeting_style": style, "traits": traits,
            "voice": voice or {}, "adult_only": adult_only,
            "builtin": True}


