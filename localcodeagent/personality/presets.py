PRESETS: dict[str, dict] = {
    p["id"]: p
    for group in (GENERAL, TECH, HUMOR, CREATIVE, GUIDANCE,
                  EFFICIENCY, ADULT)
    for p in group
}


def get_preset(preset_id: str) -> dict | None:
    return PRESETS.get(str(preset_id))


def list_presets(*, include_adult: bool = False) -> list[dict]:
    """Public preset list — adult presets are excluded entirely for
    under-18 callers (not merely flagged)."""
    return [dict(p) for p in PRESETS.values()
            if include_adult or not p.get("adult_only")]
